    // Entirely procedural fixtures: no Rockstar models, textures, or game installation.
    public static class DemoFactory
    {
        public static string[] Create(string directory)
        {
            directory = Path.GetFullPath(directory);
            if (Directory.Exists(directory) && Directory.EnumerateFileSystemEntries(directory).Any())
                directory = Path.Combine(directory, "demo-" + Guid.NewGuid().ToString("N"));
            string quay = Path.Combine(directory, "01 - Quay district");
            string yard = Path.Combine(directory, "02 - Foundry yard");
            Directory.CreateDirectory(Path.Combine(quay, "stream"));
            Directory.CreateDirectory(Path.Combine(yard, "stream"));

            var shapes = new[]
            {
                new Shape("seam_tower", new Dx.Vector3(-4, -4, 0), new Dx.Vector3(4, 4, 11), "seam_facade"),
                new Shape("seam_hall", new Dx.Vector3(-6, -4, 0), new Dx.Vector3(6, 4, 5), "seam_facade"),
                new Shape("seam_planter", new Dx.Vector3(-0.8f, -0.8f, 0), new Dx.Vector3(0.8f, 0.8f, 0.8f), "seam_paving"),
                new Shape("seam_plaza", new Dx.Vector3(-22, -15, -0.35f), new Dx.Vector3(22, 15, -0.15f), "seam_paving")
            };
            var textureDict = new TextureDictionary();
            textureDict.BuildFromTextureList(new List<Texture> { MakeTexture("seam_facade", true), MakeTexture("seam_paving", false) });
            byte[] textures = new YtdFile { TextureDict = textureDict }.Save();
            var ytyp = new YtypFile { Name = "seam_demo.ytyp", NameHash = Hash("seam_demo") };
            var archetypes = new List<Archetype>();
            foreach (var shape in shapes)
            {
                var def = new CBaseArchetypeDef { name = Hash(shape.Name), assetName = Hash(shape.Name),
                    assetType = rage__fwArchetypeDef__eAssetType.ASSET_TYPE_DRAWABLE,
                    textureDictionary = Hash("seam_materials"), bbMin = shape.Min, bbMax = shape.Max,
                    bsCentre = (shape.Min + shape.Max) / 2, bsRadius = (shape.Max - shape.Min).Length() / 2,
                    lodDist = 400, hdTextureDist = 100, flags = 32 };
                var archetype = new Archetype();
                archetype.Init(ytyp, ref def);
                archetypes.Add(archetype);
                var bytes = new YdrFile { Drawable = MakeDrawable(shape) }.Save();
                File.WriteAllBytes(Path.Combine(quay, "stream", shape.Name + ".ydr"), bytes);
                File.WriteAllBytes(Path.Combine(yard, "stream", shape.Name + ".ydr"), bytes);
            }
            ytyp.AllArchetypes = archetypes.ToArray();
            var typeBytes = ytyp.Save();
            foreach (string pack in new[] { quay, yard })
            {
                File.WriteAllBytes(Path.Combine(pack, "stream", "seam_materials.ytd"), textures);
                File.WriteAllBytes(Path.Combine(pack, "stream", "seam_demo.ytyp"), typeBytes);
                File.WriteAllText(Path.Combine(pack, "fxmanifest.lua"), "fx_version 'cerulean'\ngame 'gta5'\nthis_is_a_map 'yes'\nfiles { 'stream/*.ytyp' }\ndata_file 'DLC_ITYP_REQUEST' 'stream/*.ytyp'\n");
            }

            var quayItems = new[]
            {
                new Placement("seam_tower", -10, 1, 0), new Placement("seam_hall", 6, -7, 0),
                new Placement("seam_planter", -1, 9, 0), new Placement("seam_planter", -4, 9, 0),
                new Placement("seam_plaza", 0, 0, 0)
            };
            var yardItems = new[]
            {
                new Placement("seam_tower", -5, 2, 0), new Placement("seam_hall", 11, 5, 0),
                new Placement("seam_planter", -1, 9, 0), new Placement("seam_planter", 15, -6, 0)
            };
            WriteMap(quay, "quay_district", quayItems, archetypes);
            WriteMap(yard, "foundry_yard", yardItems, archetypes);
            WriteCollision(quay, "quay_collision", quayItems.Take(2), shapes);
            WriteCollision(yard, "yard_collision", yardItems.Take(2), shapes);
            File.WriteAllText(Path.Combine(directory, "README.txt"),
                "Seam procedural demo\r\n\r\nTwo intentionally overlapping map packs.\r\n" +
                "The planter at (-1, 9, 0) is duplicated. Towers overlap near (-7, 2, 5).\r\n" +
                "The YBNs contain independently selectable box children for collision review.\r\n" +
                "All YDR, YTD, YTYP, YMAP and YBN files were generated by Seam using the local CodeWalker library.\r\n" +
                "No game assets are included. These are test fixtures, not a production game map.\r\n");
            return new[] { quay, yard };
        }

        static void WriteMap(string folder, string name, IEnumerable<Placement> placements, List<Archetype> archetypes)
        {
            var map = new YmapFile { Name = name + ".ymap" };
            foreach (var placement in placements)
            {
                var def = new CEntityDef { archetypeName = Hash(placement.Name), position = placement.Position,
                    rotation = new Dx.Vector4(0, 0, 0, 1), scaleXY = 1, scaleZ = 1,
                    parentIndex = -1, lodDist = 400, childLodDist = -1,
                    lodLevel = rage__eLodType.LODTYPES_DEPTH_HD,
                    priorityLevel = rage__ePriorityLevel.PRI_REQUIRED, flags = 32 };
                var ent = new YmapEntityDef(map, map.AllEntities?.Length ?? 0, ref def);
                ent.SetArchetype(archetypes.First(a => a.Hash.Hash == Hash(placement.Name)));
                map.AddEntity(ent);
            }
            map.CalcExtents();
            map.CalcFlags();
            File.WriteAllBytes(Path.Combine(folder, "stream", name + ".ymap"), map.Save());
        }

        static void WriteCollision(string folder, string name, IEnumerable<Placement> placements, Shape[] shapes)
        {
            var root = new BoundComposite { Type = BoundsType.Composite };
            var children = new List<Bounds>();
            foreach (var placement in placements)
            {
                var shape = shapes.First(s => s.Name == placement.Name);
                var box = new BoundBox { Type = BoundsType.Box, BoxMin = shape.Min, BoxMax = shape.Max,
                    BoxCenter = (shape.Min + shape.Max) / 2,
                    SphereCenter = (shape.Min + shape.Max) / 2,
                    SphereRadius = (shape.Max - shape.Min).Length() / 2,
                    Margin = 0.04f, Parent = root, Transform = Dx.Matrix.Translation(placement.Position),
                    TransformInv = Dx.Matrix.Translation(-placement.Position) };
                children.Add(box);
            }
            root.Children = new ResourcePointerArray64<Bounds> { data_items = children.ToArray() };
            root.UpdateChildrenBounds();
            root.UpdateChildrenTransformations();
            root.UpdateChildrenFlags();
            var mins = children.Select(b => b.BoxMin + b.Position).ToArray();
            var maxs = children.Select(b => b.BoxMax + b.Position).ToArray();
            root.BoxMin = mins.Aggregate(Dx.Vector3.Min);
            root.BoxMax = maxs.Aggregate(Dx.Vector3.Max);
            root.BoxCenter = (root.BoxMin + root.BoxMax) / 2;
            root.SphereCenter = root.BoxCenter;
            root.SphereRadius = (root.BoxMax - root.BoxMin).Length() / 2;
            root.BuildBVH();
            File.WriteAllBytes(Path.Combine(folder, "stream", name + ".ybn"), new YbnFile { Bounds = root }.Save());
        }

        static Drawable MakeDrawable(Shape shape)
        {
            var declaration = new VertexDeclaration { Flags = (1u << 0) | (1u << 3) | (1u << 6),
                Types = VertexDeclarationTypes.GTAV1 };
            declaration.UpdateCountAndStride();
            var data = new VertexData { Info = declaration, VertexCount = 24, VertexStride = declaration.Stride,
                VertexBytes = new byte[24 * declaration.Stride] };
            var corners = new Dx.Vector3[8];
            for (int i = 0; i < 8; i++) corners[i] = new Dx.Vector3((i & 1) == 0 ? shape.Min.X : shape.Max.X,
                (i & 2) == 0 ? shape.Min.Y : shape.Max.Y, (i & 4) == 0 ? shape.Min.Z : shape.Max.Z);
            int[][] faces = { new[] { 0, 1, 3, 2 }, new[] { 4, 6, 7, 5 }, new[] { 0, 4, 5, 1 },
                new[] { 2, 3, 7, 6 }, new[] { 0, 2, 6, 4 }, new[] { 1, 5, 7, 3 } };
            var indices = new List<ushort>();
            var uv = new[] { new Dx.Vector2(0, 1), new Dx.Vector2(1, 1), new Dx.Vector2(1, 0), new Dx.Vector2(0, 0) };
            for (int face = 0; face < 6; face++)
            {
                int start = face * 4;
                var normal = Dx.Vector3.Normalize(Dx.Vector3.Cross(corners[faces[face][1]] - corners[faces[face][0]], corners[faces[face][2]] - corners[faces[face][0]]));
                for (int i = 0; i < 4; i++)
                { data.SetVector3(start + i, 0, corners[faces[face][i]]); data.SetVector3(start + i, 3, normal); data.SetVector2(start + i, 6, uv[i]); }
                foreach (int i in new[] { 0, 1, 2, 0, 2, 3 }) indices.Add((ushort)(start + i));
            }
            var texture = new TextureBase { Name = shape.Texture, NameHash = Hash(shape.Texture) };
            var shader = new ShaderFX { Name = Hash("default"), FileName = Hash("default.sps"), RenderBucketMask = 0xFF01,
                ParametersList = new ShaderParametersBlock { Count = 1, Parameters = new[] { new ShaderParameter { DataType = 0, Data = texture } },
                    Hashes = new[] { (MetaName)(uint)ShaderParamNames.DiffuseSampler } } };
            shader.ParametersList.Owner = shader;
            shader.ParameterSize = shader.ParametersList.ParametersSize;
            shader.ParameterDataSize = shader.ParametersList.ParametersDataSize;
            shader.TextureParametersCount = 1;
            var geometry = new DrawableGeometry { VertexData = data,
                VertexBuffer = new VertexBuffer { Data1 = data, Info = declaration, VertexCount = 24, VertexStride = declaration.Stride },
                IndexBuffer = new IndexBuffer { Indices = indices.ToArray() }, Shader = shader, ShaderID = 0,
                AABB = new AABB_s { Min = new Dx.Vector4(shape.Min, 0), Max = new Dx.Vector4(shape.Max, 0) } };
            var model = new DrawableModel { Geometries = new[] { geometry }, ShaderMapping = new ushort[] { 0 },
                BoundsData = new[] { geometry.AABB }, RenderMaskFlags = 0xFF,
                GeometriesCount1 = 1, GeometriesCount2 = 1, GeometriesCount3 = 1 };
            var drawable = new Drawable { Name = shape.Name, BoundingBoxMin = shape.Min, BoundingBoxMax = shape.Max,
                BoundingCenter = (shape.Min + shape.Max) / 2, BoundingSphereRadius = (shape.Max - shape.Min).Length() / 2,
                LodDistHigh = 400, LightAttributes = new ResourceSimpleList64<LightAttributes>(),
                ShaderGroup = new ShaderGroup { Shaders = new ResourcePointerArray64<ShaderFX> { data_items = new[] { shader } } } };
            drawable.DrawableModels = new DrawableModelsBlock { Owner = drawable, High = new[] { model } };
            drawable.BuildAllModels();
            drawable.BuildRenderMasks();
            return drawable;
        }

        static Texture MakeTexture(string name, bool facade)
        {
            var pixels = new byte[64 * 64 * 4];
            for (int y = 0; y < 64; y++)
                for (int x = 0; x < 64; x++)
                {
                    bool window = facade && y % 16 >= 4 && y % 16 <= 11 && x % 16 >= 4 && x % 16 <= 11;
                    bool seam = x % 16 == 0 || y % 16 == 0;
                    byte r = (byte)(window ? 53 : seam ? 133 : facade ? 199 : 156);
                    byte g = (byte)(window ? 77 : seam ? 141 : facade ? 202 : 166);
                    byte b = (byte)(window ? 81 : seam ? 138 : facade ? 193 : 159);
                    int p = (y * 64 + x) * 4;
                    pixels[p] = b; pixels[p + 1] = g; pixels[p + 2] = r; pixels[p + 3] = 255;
                }
            return new Texture { Name = name, NameHash = Hash(name), Width = 64, Height = 64, Depth = 1,
                Stride = 256, Levels = 1, Format = TextureFormat.D3DFMT_A8R8G8B8, Data = new TextureData { FullData = pixels } };
        }

        static uint Hash(string value) { JenkIndex.Ensure(value); return JenkHash.GenHash(value); }
        sealed class Shape
        {
            public readonly string Name, Texture;
            public readonly Dx.Vector3 Min, Max;
            public Shape(string name, Dx.Vector3 min, Dx.Vector3 max, string texture) { Name = name; Min = min; Max = max; Texture = texture; }
        }
        sealed class Placement
        {
            public readonly string Name;
            public readonly Dx.Vector3 Position;
            public Placement(string name, float x, float y, float z) { Name = name; Position = new Dx.Vector3(x, y, z); }
        }
    }
